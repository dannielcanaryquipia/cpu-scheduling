import { useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import LessonShell from '../components/LessonShell.jsx';
import QuestionCard from '../components/QuestionCard.jsx';
import GanttChart from '../components/GanttChart.jsx';
import { PRACTICE } from '../data/practice.js';
import { ALGO_META, simulate } from '../lib/schedulers.js';
import { buildColorMap } from '../lib/colors.js';
import { simulatorLink } from '../lib/share.js';

function Problem({ problem, number }) {
  const [showSolution, setShowSolution] = useState(false);
  const sim = useMemo(() => {
    if (!problem.processes) return null;
    return {
      result: simulate(problem.algo, problem.processes, { quantum: problem.quantum ?? 2 }),
      colorMap: buildColorMap(problem.processes),
    };
  }, [problem]);

  return (
    <section className="problem">
      <div className="problem-head">
        <span className="problem-num mono">#{number}</span>
        <h2>{problem.title}</h2>
        <span className={`badge diff-${problem.difficulty.toLowerCase()}`}>{problem.difficulty}</span>
        <span className="badge">{ALGO_META[problem.algo].short}</span>
      </div>

      <QuestionCard label="Problem" prompt={problem.prompt} options={problem.options} answer={problem.answer} explanation="Open the full solution below to see every step.">
        {problem.processes && (
          <div className="table-wrap">
            <table className="data-table given-table">
              <thead>
                <tr>
                  <th>Process</th>
                  <th>Arrival</th>
                  <th>Burst</th>
                  {problem.showPriority && <th>Priority</th>}
                </tr>
              </thead>
              <tbody>
                {problem.processes.map((p) => (
                  <tr key={p.id}>
                    <td>{p.id}</td>
                    <td>{p.at}</td>
                    <td>{p.bt}</td>
                    {problem.showPriority && <td>{p.pr}</td>}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </QuestionCard>

      <button className="btn btn-small" onClick={() => setShowSolution((s) => !s)}>
        {showSolution ? 'Hide solution' : 'Show step-by-step solution'}
      </button>

      {showSolution && (
        <div className="solution">
          <ol>
            {problem.solution.map((line) => (
              <li key={line}>{line}</li>
            ))}
          </ol>
          {sim && (
            <>
              <p className="stage-title">Gantt chart (generated by the simulator)</p>
              <GanttChart result={sim.result} colorMap={sim.colorMap} />
              <Link className="link-arrow" to={simulatorLink(problem.algo, problem.processes, problem.quantum)}>
                Replay this problem step by step in the simulator →
              </Link>
            </>
          )}
        </div>
      )}
    </section>
  );
}

export default function Practice() {
  return (
    <LessonShell title="Worked Problems" lead="Exam-style problems. Try each one on paper first, pick an answer, then open the solution to compare.">
      <div className="exam-tips">
        <p className="mini-game-title">Exam routine that always works</p>
        <ol>
          <li>Write the table: Process, AT, BT (and priority if given).</li>
          <li>Draw the Gantt chart one decision at a time. At each arrival or completion, ask: who is ready, and who does the rule pick?</li>
          <li>Read CT for each process from the right edge of its last block.</li>
          <li>Compute TAT = CT − AT, then WT = TAT − BT. Average only at the end.</li>
        </ol>
      </div>
      {PRACTICE.map((p, i) => (
        <Problem key={p.id} problem={p} number={i + 1} />
      ))}
    </LessonShell>
  );
}
